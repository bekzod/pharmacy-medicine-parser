function normalizeMedicineLanguage(value) {
  let normalized = String(value || '')
    .toLowerCase()
    .replace(/ё/g, 'е');

  for (const [pattern, replacement] of MEDICINE_LANGUAGE_NORMALIZERS) {
    normalized = normalized.replace(pattern, replacement);
  }

  return normalized;
}

module.exports = { normalizeMedicineLanguage };
